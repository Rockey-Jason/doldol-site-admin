drop function if exists public.admin_get_user_detail(uuid);
create or replace function public.admin_get_user_detail(p_user_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  result jsonb;
begin
  if not public.admin_is_authorized() then
    raise exception '관리자 권한이 없습니다.';
  end if;

  select jsonb_build_object(
    'profile', to_jsonb(u),
    'auth', case when a.id is null then null else jsonb_build_object(
      'id', a.id,
      'email', a.email,
      'email_confirmed_at', a.email_confirmed_at,
      'last_sign_in_at', a.last_sign_in_at,
      'created_at', a.created_at,
      'updated_at', a.updated_at
    ) end
  )
  into result
  from public.users u
  left join auth.users a on a.id = u.user_id
  where u.user_id = p_user_id;

  return result;
end;
$$;

revoke all on function public.admin_get_user_detail(uuid) from public;
grant execute on function public.admin_get_user_detail(uuid) to authenticated;

