-- ============================================================
-- 돌이 관리자 센터 - 회원 전체 조회/관리 확장판
-- ============================================================
-- 핵심 원칙
-- 1) 관리자 사이트 진입: is_admin=true AND user_level>=10
-- 2) 회원 목록 조회: public.users 전체를 조회
-- 3) auth.users는 LEFT JOIN하여 Auth 계정이 없는 users 행도 유지
-- 4) Auth 민감정보는 SECURITY DEFINER 함수가 필요한 필드만 반환
-- 5) service_role key는 브라우저에 노출하지 않음
-- ============================================================

create table if not exists public.admin_logs (
  id bigint generated by default as identity primary key,
  admin_user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  target_user_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.admin_logs enable row level security;

drop policy if exists "admins read admin logs" on public.admin_logs;
create policy "admins read admin logs" on public.admin_logs
for select to authenticated
using (public.admin_is_authorized());

create or replace function public.admin_is_authorized()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.users u
    where u.user_id = auth.uid()
      and u.is_admin = true
      and coalesce(u.user_level, 0) >= 10
  );
$$;

revoke all on function public.admin_is_authorized() from public;
grant execute on function public.admin_is_authorized() to authenticated;

-- ============================================================
-- 전체 회원 조회
-- ============================================================
-- 관리자 본인을 포함한 모든 public.users 행을 반환합니다.
-- is_admin/user_level로 회원을 걸러내지 않습니다.
-- auth.users가 없더라도 LEFT JOIN 때문에 users 행은 남습니다.
-- ============================================================

drop function if exists public.admin_list_users(text, integer, integer);
create or replace function public.admin_list_users(
  p_search text default null,
  p_limit integer default 500,
  p_offset integer default 0
)
returns table (
  user_id uuid,
  user_number bigint,
  login_id text,
  name text,
  profile_image text,
  user_level integer,
  doldolcoin bigint,
  exp bigint,
  exp_level integer,
  equipped_title text,
  is_admin boolean,
  suspended_until timestamptz,
  permanently_banned boolean,
  suspension_reason text,
  auth_user_id uuid,
  email text,
  email_confirmed_at timestamptz,
  last_sign_in_at timestamptz,
  auth_created_at timestamptz,
  last_seen_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    u.user_id,
    u.user_number,
    u.login_id,
    u.name,
    u.profile_image,
    u.user_level,
    coalesce(u.doldolcoin, 0),
    coalesce(u.exp, 0),
    u.exp_level,
    u.equipped_title,
    coalesce(u.is_admin, false),
    u.suspended_until,
    coalesce(u.permanently_banned, false),
    u.suspension_reason,
    a.id,
    a.email::text,
    a.email_confirmed_at,
    a.last_sign_in_at,
    a.created_at,
    a.last_sign_in_at
  from public.users u
  left join auth.users a on a.id = u.user_id
  where
    p_search is null
    or trim(p_search) = ''
    or u.login_id ilike '%' || p_search || '%'
    or u.name ilike '%' || p_search || '%'
    or a.email ilike '%' || p_search || '%'
    or cast(u.user_number as text) = trim(p_search)
  order by u.user_number nulls last, u.login_id nulls last
  limit greatest(1, least(coalesce(p_limit, 500), 1000))
  offset greatest(coalesce(p_offset, 0), 0);
$$;

revoke all on function public.admin_list_users(text, integer, integer) from public;
grant execute on function public.admin_list_users(text, integer, integer) to authenticated;

