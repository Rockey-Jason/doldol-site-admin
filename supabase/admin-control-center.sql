do $$
declare t text;
begin
 foreach t in array array['users','rockey_news','dori_box_items','rockey_news_events','admin_logs','doldolcoin_transactions'] loop
   if to_regclass('public.'||t) is not null then
     execute format('alter table public.%I enable row level security',t);
   end if;
 end loop;
end $$;

do $$ begin
 if not exists(select 1 from pg_policies where schemaname='public' and tablename='users' and policyname='admin read all users') then
  create policy "admin read all users" on public.users for select to authenticated using(public.admin_is_authorized() or user_id=auth.uid());
 end if;
 if not exists(select 1 from pg_policies where schemaname='public' and tablename='rockey_news' and policyname='admin all news') then
  create policy "admin all news" on public.rockey_news for all to authenticated using(public.admin_is_authorized()) with check(public.admin_is_authorized());
 end if;
 if not exists(select 1 from pg_policies where schemaname='public' and tablename='dori_box_items' and policyname='admin all box') then
  create policy "admin all box" on public.dori_box_items for all to authenticated using(public.admin_is_authorized()) with check(public.admin_is_authorized());
 end if;
 if not exists(select 1 from pg_policies where schemaname='public' and tablename='rockey_news_events' and policyname='admin all events') then
  create policy "admin all events" on public.rockey_news_events for all to authenticated using(public.admin_is_authorized()) with check(public.admin_is_authorized());
 end if;
