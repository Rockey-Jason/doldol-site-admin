create or replace function public.admin_update_user(
  p_user_id uuid,
  p_doldolcoin bigint,
  p_exp bigint,
  p_user_level integer
) returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.admin_is_authorized() then
    raise exception '관리자 권한이 없습니다.';
  end if;

  update public.users
  set doldolcoin = p_doldolcoin,
      exp = p_exp,
      user_level = p_user_level
  where user_id = p_user_id;

  if not found then
    raise exception '회원을 찾을 수 없습니다.';
  end if;

  insert into public.admin_logs(admin_user_id, action, target_user_id, details)
  values (
    auth.uid(),
    'USER_UPDATE',
    p_user_id,
    jsonb_build_object('coins',p_doldolcoin,'exp',p_exp,'level',p_user_level)
  );
end;
$$;

create or replace function public.admin_adjust_coins(
  p_user_id uuid,
  p_amount bigint,
  p_reason text
) returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  if not public.admin_is_authorized() then
    raise exception '관리자 권한이 없습니다.';
  end if;

  update public.users
  set doldolcoin = coalesce(doldolcoin,0) + p_amount
  where user_id = p_user_id;

  if not found then
    raise exception '회원을 찾을 수 없습니다.';
  end if;

  insert into public.admin_logs(admin_user_id,action,target_user_id,details)
  values(
    auth.uid(),
    'COIN_ADJUST',
    p_user_id,
    jsonb_build_object('amount',p_amount,'reason',coalesce(p_reason,''))
  );
end;
$$;

