create table if not exists public.doldolcoin_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  amount bigint not null,
  balance_after bigint,
  reason text not null default '',
  source text not null default 'unknown',
  actor_user_id uuid,
  created_at timestamptz not null default now()
);

create index if not exists doldolcoin_transactions_user_idx
on public.doldolcoin_transactions(user_id, created_at desc);

alter table public.doldolcoin_transactions enable row level security;

drop policy if exists "admins read coin ledger" on public.doldolcoin_transactions;
create policy "admins read coin ledger" on public.doldolcoin_transactions
for select to authenticated
using (public.admin_is_authorized());

create or replace function public.log_doldolcoin_change()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if coalesce(new.doldolcoin,0) is distinct from coalesce(old.doldolcoin,0) then
    insert into public.doldolcoin_transactions(
      user_id, amount, balance_after, reason, source, actor_user_id
    ) values (
      new.user_id,
      coalesce(new.doldolcoin,0) - coalesce(old.doldolcoin,0),
      coalesce(new.doldolcoin,0),
      '돌돌코인 잔액 변경',
      'users_update',
      auth.uid()
    );
  end if;
  return new;
end;
$$;

drop trigger if exists trg_log_doldolcoin_change on public.users;
create trigger trg_log_doldolcoin_change
after update of doldolcoin on public.users
for each row execute function public.log_doldolcoin_change();

revoke all on table public.doldolcoin_transactions from anon;
grant select on table public.doldolcoin_transactions to authenticated;

